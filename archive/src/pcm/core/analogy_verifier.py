# ---------------------------------------------------------------------------
# Analogy Verifier
# ---------------------------------------------------------------------------

class AnalogyVerifier:
    """
    Validates analogies for mathematical soundness.

    Scoring thresholds:
      - score >= 70 : PASS  (accept as-is)
      - 50 <= score < 70 : WARN  (add scope-limiting prefix, then accept)
      - score < 50 : FAIL  (reject; caller can trigger regeneration)
    """

    MAX_RETRIES = 2
    PASS_THRESHOLD = 70
    WARN_THRESHOLD = 50

    SCOPE_LIMITER_PREFIX = (
        "직관적 이해를 위한 비유로, "
        "수학적으로 엄밀하지 않을 수 있습니다: "
    )

    def __init__(
        self,
        model: str = "qwen2.5:7b",
        ollama_url: str = "http://localhost:11434/api/generate",
        misconceptions: Optional[List[MisconceptionEntry]] = None,
    ):
        self.model = model
        self.ollama_url = ollama_url
        self.misconceptions = misconceptions if misconceptions is not None else MISCONCEPTIONS

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def verify(
        self,
        analogy_text: str,
        formal_definition: str,
        domain: str = "mathematics",
    ) -> VerificationResult:
        """
        Verify a single analogy.

        Parameters
        ----------
        analogy_text:
            The analogy/motivation text to verify (Korean).
        formal_definition:
            The corresponding formal mathematical definition (used as context).
        domain:
            Mathematical domain (e.g. "algebra", "topology").

        Returns
        -------
        VerificationResult
        """
        # Step 1: misconception dictionary check (fast, no LLM)
        misconception_hit, misconception_name, why_wrong = self._check_misconceptions(analogy_text)
        if misconception_hit:
            return VerificationResult(
                passed=False,
                score=0,
                level="FAIL",
                reason=f"알려진 오개념 패턴 감지: {misconception_name}. {why_wrong}",
                analogy=analogy_text,
                flagged_misconception=misconception_name,
            )

        # Step 2: LLM critic evaluation
        score, reason = self._evaluate_with_llm(analogy_text, formal_definition, domain)

        level, modified_analogy = self._decide(score, analogy_text)
        return VerificationResult(
            passed=(level != "FAIL"),
            score=score,
            level=level,
            reason=reason,
            analogy=modified_analogy,
        )

    def verify_and_fix(
        self,
        analogy_text: str,
        formal_definition: str,
        domain: str = "mathematics",
        regenerate_fn: Optional[Callable[[], str]] = None,
    ) -> VerificationResult:
        """
        Verify and optionally regenerate on FAIL (up to MAX_RETRIES times).

        Parameters
        ----------
        analogy_text:
            Initial analogy to verify.
        formal_definition:
            Formal definition for context.
        domain:
            Mathematical domain.
        regenerate_fn:
            Callable that returns a new analogy string.
            If None, does not retry on FAIL.

        Returns
        -------
        VerificationResult of the best accepted result, or last FAIL if all retries exhausted.
        """
        result = self.verify(analogy_text, formal_definition, domain)

        if result.passed or regenerate_fn is None:
            return result

        for attempt in range(self.MAX_RETRIES):
            new_analogy = regenerate_fn()
            if not new_analogy:
                break
            result = self.verify(new_analogy, formal_definition, domain)
            if result.passed:
                return result

        # All retries exhausted; return last result (FAIL) with warning note
        result.reason = f"[최대 재시도 도달] {result.reason}"
        return result

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _check_misconceptions(self, analogy_text: str):
        """
        Check analogy against built-in misconception dictionary.

        Returns (hit: bool, concept_name: str, why_wrong: str)
        """
        for entry in self.misconceptions:
            if re.search(entry.bad_pattern, analogy_text, re.IGNORECASE):
                return True, entry.concept, entry.why_wrong
        return False, "", ""

    def _evaluate_with_llm(
        self,
        analogy_text: str,
        formal_definition: str,
        domain: str,
    ):
        """
        Ask LLM (math professor persona) to score the analogy 0-100.

        Returns (score: int, reason: str). Falls back to (75, "LLM 불가") on failure.
        """
        prompt = (
            f"당신은 엄격한 수학 교수입니다. 다음 수학적 비유를 평가하세요.\n\n"
            f"[공식 정의 ({domain})]:\n{formal_definition[:400]}\n\n"
            f"[비유/직관 설명]:\n{analogy_text}\n\n"
            f"다음 기준으로 0-100점 사이의 점수를 매기세요:\n"
            f"- 수학적 정확성 (40점): 비유가 공식 정의와 모순되지 않는가?\n"
            f"- 범위 명확성 (25점): 비유의 적용 한계가 명시되어 있는가?\n"
            f"- 오개념 위험 (20점): 알려진 수학적 오개념을 유발하지 않는가?\n"
            f"- 도메인 적합성 (15점): 해당 분야 독자에게 적합한가?\n\n"
            f"반드시 다음 형식으로만 답하세요:\n"
            f"SCORE: <숫자>\nREASON: <한 문장 이유>"
        )

        try:
            resp = requests.post(
                self.ollama_url,
                json={
                    "model": self.model,
                    "prompt": prompt,
                    "stream": False,
                    "options": {"temperature": 0.1, "num_predict": 100},
                },
                timeout=45,
            )
            resp.raise_for_status()
            text = resp.json().get("response", "")
            score = self._parse_score(text)
            reason = self._parse_reason(text)
            return score, reason
        except Exception:
            # Graceful fallback: assume acceptable (score 75)
            return 75, "LLM 평가 불가 - 기본값 75 적용"

    def _parse_score(self, llm_response: str) -> int:
        """Extract integer score from LLM response. Defaults to 75 on parse failure."""
        match = re.search(r"SCORE\s*:\s*(\d+)", llm_response, re.IGNORECASE)
        if match:
            return min(100, max(0, int(match.group(1))))
        # Fallback: look for any number 0-100 in the text
        numbers = re.findall(r"\b([0-9]{1,3})\b", llm_response)
        for n in numbers:
            v = int(n)
            if 0 <= v <= 100:
                return v
        return 75

    def _parse_reason(self, llm_response: str) -> str:
        """Extract reason from LLM response."""
        match = re.search(r"REASON\s*:\s*(.+)", llm_response, re.IGNORECASE)
        if match:
            return match.group(1).strip()
        return llm_response.strip()[:200]

    def _decide(self, score: int, analogy_text: str):
        """
        Map score to decision level and possibly modify analogy.

        Returns (level: str, modified_analogy: str)
        """
        if score >= self.PASS_THRESHOLD:
            return "PASS", analogy_text
        if score >= self.WARN_THRESHOLD:
            modified = self.SCOPE_LIMITER_PREFIX + analogy_text
            return "WARN", modified
        return "FAIL", analogy_text
