"""
Analogy Verifier for PCM Translation Pipeline.

Validates that analogies generated by MotivationAgent are mathematically
sound and do not introduce known misconceptions.

Verification flow:
  1. Check against built-in misconception dictionary (O(n), fast)
  2. LLM critic evaluation with math professor persona (0-100 score)
  3. Decision: PASS (>=70) / WARN (50-69, add scope limiter) / FAIL (<50, reject)

If FAIL, caller can supply a regenerate_fn; the verifier retries up to
MAX_RETRIES times before accepting the last result with a warning.
"""

from __future__ import annotations

import re
import requests
from dataclasses import dataclass, field
from typing import Callable, List, Optional


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------

@dataclass
class VerificationResult:
    """Result of a single analogy verification."""

    passed: bool            # True for PASS or WARN
    score: int              # 0-100
    level: str              # "PASS" | "WARN" | "FAIL"
    reason: str             # Human-readable explanation
    analogy: str            # Possibly modified analogy (scope limiter added for WARN)
    flagged_misconception: Optional[str] = None  # Name of matched misconception if any


@dataclass
class MisconceptionEntry:
    """A known bad analogy pattern with explanation."""

    concept: str
    bad_pattern: str        # regex or keyword pattern
    why_wrong: str
    good_alternative: str = ""


